using ComputerVision.Models;

namespace ComputerVision.Utils;

public class TimeComplexityAnalyzer
{
    private readonly Dictionary<string, Statistics> _samplesStats = [];
    private readonly Dictionary<string, Statistics> _stepsStats = [];
    private readonly Dictionary<(string, string),
        Statistics> _samplesWithStepsStats = [];

    /// <summary>
    /// Accumulates total, per-stage and per-image stage timings.
    /// </summary>
    /// <param name="sampleName">
    /// The name grouping repeated measurements of the same image.
    /// </param>
    /// <param name="imageProfilingResult">
    /// The recorded total time and individual stage times.
    /// </param>
    public void AddResult(string sampleName,
        ImageProfilingResult imageProfilingResult)
    {

        // Stats for total elapsed time of given sample
        if (!_samplesStats.TryGetValue(sampleName, out Statistics? sampleStat))
        {
            _samplesStats.Add(sampleName, sampleStat = new Statistics());
        }

        sampleStat.AddValue((float)imageProfilingResult.ElapsedMilliseconds);

        // Stats for each elapsed time in steps
        for (int i = 0; i < imageProfilingResult.StepResults.Count; i++)
        {
            StepProfilingResult stepResult =
                imageProfilingResult.StepResults[i];
            string stepNameKey = $"{i:D2} {stepResult.StepName}";

            if (!_stepsStats.TryGetValue(stepNameKey, out Statistics? stepStat))
            {
                _stepsStats.Add(stepNameKey, stepStat = new Statistics());
            }

            stepStat.AddValue((float)stepResult.ElapsedMilliseconds);
            (string sampleName, string stepNameKey) key = (sampleName,
                stepNameKey);

            if (!_samplesWithStepsStats.TryGetValue(key,
                out Statistics? sampleStepStat))
            {
                _samplesWithStepsStats.Add(key,
                    sampleStepStat = new Statistics());
            }

            sampleStepStat.AddValue((float)stepResult.ElapsedMilliseconds);
        }
    }

    /// <summary>
    /// Prints selected timing statistics and optional stage aggregates.
    /// </summary>
    /// <param name="stepIndexes">
    /// Optional indexes into the alphabetically ordered stage names.
    /// </param>
    /// <param name="printStepAggregates">
    /// Whether to append statistics pooled across images.
    /// </param>
    public void PrintConsoleReport(IEnumerable<int>? stepIndexes = null,
        bool printStepAggregates = true)
    {

        // This console lines formatting are generated by ChatGPT
        Console.WriteLine();
        Console.WriteLine("=== AVERAGE TIMINGS PER IMAGE ===");
        var orderedSteps = _stepsStats.Keys.OrderBy(k => k).ToList();
        List<int> selectedIndexes = stepIndexes?.Distinct().Where(i => i >= 0
            && i < orderedSteps.Count).ToList() ?? [..Enumerable.Range(0,
            orderedSteps.Count)];
        Console.Write("Image".PadRight(14));
        Console.Write("Total (ms)".PadRight(24));

        foreach (int idx in selectedIndexes)
        {
            Console.Write(orderedSteps[idx].PadRight(24));
        }

        Console.WriteLine();
        Console.WriteLine(new string('-',
            14 + 24 + (selectedIndexes.Count * 24)));

        foreach (string? sample in _samplesStats.Keys.OrderBy(s => s))
        {
            Statistics stat = _samplesStats[sample];
            (float l, float h) = stat.ConfidenceInterval95();
            Console.Write(sample.PadRight(14));
            Console.Write($"{stat.Mean:F2} <{l:F2};{h:F2}>".PadRight(24));

            foreach (int idx in selectedIndexes)
            {
                string stepName = orderedSteps[idx];

                if (_samplesWithStepsStats.TryGetValue((sample, stepName),
                    out Statistics? stepStat))
                {
                    (float sl, float sh) = stepStat.ConfidenceInterval95();
                    Console.Write($"{stepStat.Mean:F2} <{sl:F2};{sh:F2}>"
                        .PadRight(24));
                }
                else
                {
                    Console.Write("n/a".PadRight(24));
                }
            }

            Console.WriteLine();
        }

        if (!printStepAggregates)
        {
            return;
        }

        Console.WriteLine();
        Console.WriteLine("=== AVERAGE TIMINGS PER STEP (GLOBAL) ===");
        Console.WriteLine();
        Console.WriteLine("Step Name".PadRight(36) + "Mean (ms)".PadRight(14) +
            "95% CI");
        Console.WriteLine(new string('-', 36 + 14 + 20));
        float totalStepMean = 0f;

        foreach (int idx in selectedIndexes)
        {
            string name = orderedSteps[idx];
            Statistics s = _stepsStats[name];
            (float l, float h) = s.ConfidenceInterval95();
            totalStepMean += s.Mean;
            Console.Write($"{name}".PadRight(36));
            Console.Write($"{s.Mean:F2}".PadRight(14));
            Console.WriteLine($"<{l:F2};{h:F2}>");
        }

        Console.WriteLine(new string('-', 36 + 14 + 20));
        Console.WriteLine("SUM (all steps)".PadRight(36) + totalStepMean
            .ToString("F2").PadRight(14) + "-");
    }

    /// <summary>
    /// Writes semicolon-separated timing reports to the desktop.
    /// </summary>
    /// <param name="name">
    /// The optional filename label appended after the timestamp.
    /// </param>
    /// <param name="stepIndexes">
    /// Optional indexes into the alphabetically ordered stage names.
    /// </param>
    /// <param name="exportStepsAggregation">
    /// Whether to create the additional per-stage CSV file.
    /// </param>
    /// <remarks>
    /// Filenames include a timestamp and the optional supplied label.
    /// </remarks>
    public void ExportCsv(string? name = "analysis",
        IEnumerable<int>? stepIndexes = null,
        bool exportStepsAggregation = true)
    {

        // This csv lines formatting are generated by ChatGPT
        string desktop = Environment.GetFolderPath(Environment.SpecialFolder
            .DesktopDirectory);
        string timestamp = DateTime.Now.ToString("yyyyMMdd_HHmmss");
        string fileImages = Path.Combine(desktop, $"{timestamp}_{name}.csv");
        string fileSteps = Path.Combine(desktop,
            $"{timestamp}_{name}_steps.csv");
        var orderedSteps = _stepsStats.Keys.OrderBy(k => k).ToList();
        List<int> selectedIndexes = stepIndexes?.Distinct().Where(i => i >= 0
            && i < orderedSteps.Count).ToList() ?? [..Enumerable.Range(0,
            orderedSteps.Count)];

        // --------------------------
        // 1) CSV – per-image results
        // --------------------------
        using (var sw = new StreamWriter(fileImages))
        {

            // Header
            var header = new List<string>
            {
                "sample",
                "total_mean",
                "total_ci_lower",
                "total_ci_upper"
            };

            foreach (int idx in selectedIndexes)
            {
                string stepName = orderedSteps[idx];
                header.Add($"{stepName}_mean");
                header.Add($"{stepName}_ci_lower");
                header.Add($"{stepName}_ci_upper");
            }

            sw.WriteLine(string.Join(";", header));

            // Rows
            foreach (string? sample in _samplesStats.Keys.OrderBy(s => s))
            {
                Statistics stat = _samplesStats[sample];
                (float l, float h) = stat.ConfidenceInterval95();
                var row = new List<string>
                {
                    sample,
                    stat.Mean.ToString("F4"),
                    l.ToString("F4"),
                    h.ToString("F4")
                };

                foreach (int idx in selectedIndexes)
                {
                    string stepName = orderedSteps[idx];

                    if (_samplesWithStepsStats.TryGetValue((sample, stepName),
                        out Statistics? stepStat))
                    {
                        (float sl, float sh) = stepStat.ConfidenceInterval95();
                        row.Add(stepStat.Mean.ToString("F4"));
                        row.Add(sl.ToString("F4"));
                        row.Add(sh.ToString("F4"));
                    }
                    else
                    {
                        row.Add("");
                        row.Add("");
                        row.Add("");
                    }
                }

                sw.WriteLine(string.Join(";", row));
            }
        }

        // ---------------------------------------
        // 2) CSV – aggregated results per step
        // ---------------------------------------
        if (!exportStepsAggregation)
        {
            return;
        }

        using (var sw = new StreamWriter(fileSteps))
        {

            // Header
            sw.WriteLine("step;mean;ci_lower;ci_upper");

            foreach (int idx in selectedIndexes)
            {
                string stepName = orderedSteps[idx];
                Statistics stat = _stepsStats[stepName];
                (float l, float h) = stat.ConfidenceInterval95();
                var row = new List<string>
                {
                    $"{stepName}",
                    stat.Mean.ToString("F4"),
                    l.ToString("F4"),
                    h.ToString("F4")
                };
                sw.WriteLine(string.Join(";", row));
            }
        }
    }

    /// <summary>
    /// Removes all collected timing groups.
    /// </summary>
    public void Clear()
    {
        _samplesStats.Clear();
        _stepsStats.Clear();
        _samplesWithStepsStats.Clear();
    }
}
